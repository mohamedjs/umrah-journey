// all lines that a voice actor / TTS should record (used by tools/export_voice_lines.mjs)
export function allLines() {
  const out = [];
  const walk = v => {
    if (!v) return;
    if (Array.isArray(v)) return v.forEach(walk);
    if (v.id && v.text) return out.push(v);
    if (v.a) { out.push({ id: v.a.id + '-q', who: 'player', text: v.q }); return walk(v.a); }
    if (typeof v === 'object') Object.values(v).forEach(walk);
  };
  walk(HOME); walk(AIRPORT); walk(PLANE); walk(MAKKAH); walk(TAWAF); walk(SAI); walk(QA);
  return out;
}
